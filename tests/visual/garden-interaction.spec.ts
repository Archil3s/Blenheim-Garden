const fixture: PlannerPlan = { beds: [{ id: 1, name: "Salad bed", x: 10, y: 10, w: 25, h: 20 }],
  plantingAreas: [{ id: "salad", bedId: 1, crop: "Lettuce", variety: "Butterhead", cropIcon: "", spacingCm: 30, x: 0, y: 0, w: 100, h: 100, count: 2, pattern: "grid", iconSize: 16, visualSpacing: "normal", placements: [{ id: "a", x: 30, y: 30 }, { id: "b", x: 70, y: 70 }] }], rows: [],
  objects: [{ id: "raised", type: "structure", kind: "raised-bed-timber", x: 550, y: 550, widthCm: 240, depthCm: 160, heightCm: 60, rotationDeg: 30, label: "Raised bed" }] };
const read = (page: Page): Promise<PlannerPlan> => page.evaluate(() => JSON.parse(localStorage.getItem("blenheim-garden-live-plan")!));

test("planting respects owners, locks, mixed spacing and small container centres", () => {
  const small: PlannerPlan = { beds: [], rows: [], plantingAreas: [], objects: [{ ...fixture.objects[0], id: "pot", type: "structure", kind: "pot", x: 400, y: 400, widthCm: 40, depthCm: 40, heightCm: 40, rotationDeg: 20 }] as PlannerPlan["objects"] };
  const soil = plantingSurfaces(small)[0];
  const points = cropPlacementPoints(small, "Lettuce", soil, null, "fill", "object:pot", 35);
  expect(points).toEqual([{ x: 400, y: 400 }]);
  expect(plantingLocationIssue(small, { x: 600, y: 600 }, "object:pot")).toContain("Stay on");
  expect(() => addCropPoints(small, "Lettuce", "Butterhead", [{ x: 600, y: 600 }], "object:pot")).toThrow(/Stay on/);
  const planted = addCropPoints(small, "Lettuce", "Butterhead", points, "object:pot", 35);
  expect(cropPlacementPoints(planted, "Lettuce", { x: 410, y: 400 }, null, "plant", "object:pot", 35)).toEqual([]);
  expect(plantingPointFeedback(planted, { x: 405, y: 400 }, 35, "object:pot")).toContain("Too close");
  expect(cropPlacementPoints({ ...small, objectLocks: ["object:pot"] }, "Lettuce", soil, null, "fill", "object:pot", 35)).toEqual([]);
  expect(() => addCropPoints({ ...small, objectLocks: ["object:pot"] }, "Lettuce", "Butterhead", points, "object:pot")).toThrow(/Unlock/);
  const ground = { ...planted, objects: [], rows: [{ ...planted.rows[0], surfaceId: undefined }] };
  expect(cropPlacementPoints(ground, "Tomato", { x: 430, y: 400 }, null, "plant", undefined, 75)).toEqual([]);
  expect(cropPlacementPoints(ground, "Tomato", { x: 460, y: 400 }, null, "plant", undefined, 75)).toHaveLength(1);
  expect(cropPlacementPoints(ground, "Tomato", { x: -10, y: 400 }, null, "plant")).toEqual([]);
  expect(plantingPointFeedback(ground, { x: 1000, y: 400 }, 75)).toContain("garden boundary");
});

